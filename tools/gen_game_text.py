#!/usr/bin/env python3
"""Bake Pixel Keep's Chinese and English labels into 1-bit masks: main/game/game_text.h

Run with a Python that has Pillow:  /opt/homebrew/bin/python3.13 tools/gen_game_text.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = "/Library/Fonts/NotoSansCJKsc-Bold.otf"
OUT = ROOT / "main" / "game" / "game_text.h"

TEXTS = [
    ("像素守城", "Pixel Keep", 20), ("点一下 开始", "Tap to play", 12),
    ("点一下 再来", "Tap to retry", 12), ("最高", "Best", 12),
    ("摇一摇 放炸弹", "Shake for a bomb", 12), ("城破了", "Castle fell", 18),
    ("坚守了", "Held for", 12), ("新纪录!", "New best!", 12), ("连击", "Combo", 12),
    ("好!", "Nice!", 24), ("妙!", "Great!", 24), ("爽!", "Sweet!", 24), ("神!", "Wow!", 24),
    ("果冻大王 来了!", "Jelly King!", 12), ("挡住", "Blocked", 12),
    ("连射", "Rapid fire", 12), ("护盾", "Shield", 12), ("轰!", "Boom!", 12),
    ("充能中", "Charging", 12), ("炸弹", "Bomb", 12),
]


def bake(text, size):
    w, h = size * len(text) + 4, size + 6
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((2, h / 2), text, font=ImageFont.truetype(FONT, size), fill=255, anchor="lm")
    px = img.load()
    on = [(x, y) for y in range(h) for x in range(w) if px[x, y] > 120]
    mw = max(x for x, _ in on) + 1
    rows = []
    for y in range(h):
        bits = [1 if px[x, y] > 120 else 0 for x in range(mw)]
        bits += [0] * (-len(bits) % 8)
        rows += [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
    return mw, h, rows


def main():
    out = ["// Generated by tools/gen_game_text.py - do not edit.", "#pragma once", "#include <stdint.h>", "",
           "struct LabelBitmap { const char* key; uint8_t w, h; const uint8_t* bits; };", ""]
    for language, column in (("ZH", 0), ("EN", 1)):
        table = []
        for index, entry in enumerate(TEXTS):
            key, _, size = entry
            width, height, data = bake(entry[column], size)
            name = f"{language}_{index}"
            out.append(f"static const uint8_t {name}[] = {{{','.join(map(str, data))}}};")
            table.append(f'    {{"{key}", {width}, {height}, {name}}},')
        out += ["", f"static const LabelBitmap LABELS_{language}[] = {{", *table, "};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT} ({len(TEXTS)} strings)")


if __name__ == "__main__":
    main()
